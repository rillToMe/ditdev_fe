export type PixelIconName = keyof typeof ICONS

interface PixelIconProps {
  name: PixelIconName
  size?: number
  className?: string
  style?: CSSProperties
  title?: string
}

export default function PixelIcon({ name, size = 16, className, style, title }: PixelIconProps) {
  const grid = ICONS[name]
  const h = grid.length
  const w = grid[0].length
  const cells: { x: number; y: number }[] = []

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (grid[y][x] === '#') cells.push({ x, y })
    }
  }

  return (
    <svg
      viewBox={`0 0 ${w} ${h}`}
      width={size}
      height={size}
      className={className}
      style={style}
      fill="currentColor"
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
    >
      {title && <title>{title}</title>}
      {cells.map((c, i) => (
        <rect key={i} x={c.x} y={c.y} width={1} height={1} />
      ))}
    </svg>
  )
}
